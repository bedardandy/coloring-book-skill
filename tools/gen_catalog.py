#!/usr/bin/env python3
"""Generate reference/catalog.md — a grouped index of every charlib/scenes
helper with the first line of its docstring, plus an interest→helper map.

LLM skill users stop grepping a 4,000-line module: SKILL.md points here.
Deterministic output; re-run whenever helpers are added:

    python tools/gen_catalog.py
"""
