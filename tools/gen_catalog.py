def parse_module(path):
    """Yield (section, [(name, first_docstring_line), ...]) in file order."""
    section = "helpers"
    groups = []
    with open(path) as fh:
        lines = fh.readlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        m = re.match(r"# -+ (.+)", ln.strip())
        if m:
            section = m.group(1).strip()
            i += 1
            continue
        m = re.match(r"^def (\w+)\(", ln)
        if m and not m.group(1).startswith("_"):
            name = m.group(1)
            doc = ""
            j = i + 1
            if j < len(lines) and lines[j].strip().startswith('"""'):
                doc = lines[j].strip().strip('"')
                if len(lines[j].strip()) == 3:  # multiline docstring
                    if j + 1 < len(lines):
                        doc = lines[j + 1].strip()
            groups.append((section, name, doc.splitlines()[0] if doc else ""))
        i += 1
    return groups


def main():
    charlib = parse_module(os.path.join(ROOT, "lib", "charlib.py"))
    scenes = parse_module(os.path.join(ROOT, "lib", "scenes.py"))
    photolib = parse_module(os.path.join(ROOT, "lib", "photolib.py"))

    out = ["# Helper catalog",
           "",
           "Auto-generated by `tools/gen_catalog.py` — re-run after adding",
           "helpers. Signatures live in `lib/charlib.py` / `lib/scenes.py`.",
           ""]
    out += ["## Find helpers by interest", ""]
    for interest, names in INTERESTS.items():
        out.append(f"- **{interest}**: `{names.replace(' ', '` `')}`")
    out.append("")

    out += ["## charlib", ""]
    last = None
    for section, name, doc in charlib:
        if section != last:
            out += [f"### {section}", ""]
            last = section
        doc = f" — {doc}" if doc else ""
        out.append(f"- `{name}`{doc}")
    out.append("")

    if scenes:
        out += ["## scenes (scene kits — composite backgrounds)", ""]
        for section, name, doc in scenes:
            doc = f" — {doc}" if doc else ""
            out.append(f"- `{name}`{doc}")
        out.append("")

    if photolib:
        out += ["## photolib (photo → coloring outline)", ""]
        for section, name, doc in photolib:
            doc = f" — {doc}" if doc else ""
            out.append(f"- `{name}`{doc}")
        out.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}: {len(charlib)} charlib helpers, {len(scenes)} scenes")


if __name__ == "__main__":
    main()
